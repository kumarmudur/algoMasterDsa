// Length of a String

// Example 1:
// Input: s = "hello"

// Output: 5

// Example 2:
// Input: s = "open ai"

// Output: 7

// Constraints:
// 0 <= s.length <= 10^4
// s consists of printable ASCII characters.

// solution 1: Using length property
// time: O(1) | space: O(1)
/**
 * @param {string} s
 * @return {number}
 */
const lengthOfString = (s) => {
  return s.length;
};
